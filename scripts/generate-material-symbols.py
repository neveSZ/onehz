#!/usr/bin/env python3
"""Regenerate the bundled Material Symbols icon set.

OneHZ used to depend on compose-material-icons-extended for 57 icons, which adds
several megabytes to the APK. The icons are now bundled as vector drawables and
exposed through `AppIcons`, generated by this script.

Usage:
    python scripts/generate-material-symbols.py

Icons are downloaded from the Material Symbols static release endpoint and converted
to Android VectorDrawable. Keep the icon list sorted to keep the diff stable.
"""

